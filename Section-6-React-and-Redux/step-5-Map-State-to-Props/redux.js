// ============================================================================
// REACT REDUX
// STEP 5 - REDUX FILE
// MAP STATE TO PROPS
// ============================================================================
//
// This file contains our Redux state and reducer.
//
// React will access this state through mapStateToProps().
//
// ============================================================================

// ============================================================================
// ACTION TYPES
// ============================================================================

const INCREMENT = "INCREMENT";

const DECREMENT = "DECREMENT";

// ============================================================================
// INITIAL STATE
// ============================================================================

const initialState = 0;

// ============================================================================
// REDUCER
// ============================================================================

const counterReducer = (state = initialState, action) => {
  switch (action.type) {
    case INCREMENT:
      return state + 1;

    case DECREMENT:
      return state - 1;

    default:
      return state;
  }
};

// ============================================================================
// CREATE REDUX STORE
// ============================================================================

const store = Redux.createStore(counterReducer);
