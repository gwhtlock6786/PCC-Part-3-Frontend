// ============================================================================
// ACTION TYPES
// ============================================================================

const INCREMENT = "INCREMENT";

const DECREMENT = "DECREMENT";

const ADD_MESSAGE = "ADD_MESSAGE";

// ============================================================================
// INITIAL STATE
// ============================================================================

const initialState = {
  count: 0,

  messages: [
    "Redux stores shared application state.",

    "React receives Redux state through props.",
  ],
};

// ============================================================================
// ACTION CREATORS
// ============================================================================

const increment = () => {
  return {
    type: INCREMENT,
  };
};

const decrement = () => {
  return {
    type: DECREMENT,
  };
};

const addMessage = (message) => {
  return {
    type: ADD_MESSAGE,

    message: message,
  };
};

// ============================================================================
// REDUCER
// ============================================================================

const reducer = (state = initialState, action) => {
  switch (action.type) {
    // ========================================================================
    // INCREMENT
    // ========================================================================

    case INCREMENT:
      return {
        ...state,

        count: state.count + 1,
      };

    // ========================================================================
    // DECREMENT
    // ========================================================================

    case DECREMENT:
      return {
        ...state,

        count: state.count - 1,
      };

    // ========================================================================
    // ADD MESSAGE
    // ========================================================================

    case ADD_MESSAGE:
      return {
        ...state,

        messages: [...state.messages, action.message],
      };

    // ========================================================================
    // DEFAULT
    // ========================================================================

    default:
      return state;
  }
};

// ============================================================================
// CREATE STORE
// ============================================================================

const store = Redux.createStore(reducer);
